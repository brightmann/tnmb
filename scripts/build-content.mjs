// Generates lib/generated-posts.js from writings/*.md and content/*.md at build time.
//
// Replaces the old webpack raw-loader + require.context approach (and dynamic
// `import('../../writings/${slug}.md')`), which cannot work on Cloudflare
// Workers. All markdown is parsed with gray-matter at build time and bundled
// as a plain JS module — no filesystem access at request time.
import { readFile, writeFile, readdir, mkdir } from 'node:fs/promises'
import { join, basename } from 'node:path'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const matter = require('gray-matter')

const root = new URL('../', import.meta.url).pathname

async function loadDir(dirName) {
  const dir = join(root, dirName)
  let files
  try {
    files = (await readdir(dir)).filter((f) => f.endsWith('.md'))
  } catch {
    return []
  }
  const items = []
  for (const file of files) {
    const slug = basename(file, '.md')
    const raw = await readFile(join(dir, file), 'utf8')
    const { data, content } = matter(raw)
    items.push({ slug, data, content })
  }
  // Newest first, matching the old require.context sort order.
  items.sort((a, b) => new Date(b.data.date) - new Date(a.data.date))
  return items
}

const writings = await loadDir('writings')
const posts = await loadDir('content')

await mkdir(join(root, 'lib'), { recursive: true })

const out = `// GENERATED by scripts/build-content.mjs — do not edit.
export const writings = ${JSON.stringify(writings)};
export const posts = ${JSON.stringify(posts)};
`

await writeFile(join(root, 'lib', 'generated-posts.js'), out)
console.log(
  `wrote lib/generated-posts.js with ${writings.length} writings and ${posts.length} posts`
)
